# tools/test_zbb.s
# Zbb 拡張 10 命令 (min, max, minu, maxu, andn, orn, xnor, clz, sext.b, sext.h) 自己診断テスト
# すべて成功すると UART に "123456789APASS\n" に続けて 16B のカウンタ値を出力し、a0 = 1 で停止

.text
main:
    li   s11, 0x10000000       # UART TX アドレス

    # =====================================================
    # Test 1: min (符号付き最小値)
    # =====================================================
    li   t0, -10
    li   t1, 5
    min  t2, t0, t1            # min(-10, 5) -> -10
    li   t3, -10
    li   a0, '1'
    nop
    bne  t2, t3, fail

    li   t0, -25
    li   t1, -8
    min  t2, t0, t1            # min(-25, -8) -> -25
    li   t3, -25
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '1'

    # =====================================================
    # Test 2: max (符号付き最大値 & Q16.16 abs イディオム)
    # =====================================================
    li   t0, -10
    li   t1, 5
    max  t2, t0, t1            # max(-10, 5) -> 5
    li   t3, 5
    li   a0, '2'
    bne  t2, t3, fail

    # Q16.16 の -1.0 (0xFFFF0000 = -65536) の絶対値: max(x, -x) -> +1.0 (65536)
    li   t0, -65536
    sub  t1, x0, t0
    max  t2, t0, t1
    li   t3, 65536
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '2'

    # =====================================================
    # Test 3: minu (符号なし最小値)
    # =====================================================
    li   t0, -1                # 0xFFFFFFFF (符号なし最大)
    li   t1, 5                 # 0x00000005
    minu t2, t0, t1            # minu(0xFFFFFFFF, 5) -> 5
    li   t3, 5
    li   a0, '3'
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '3'

    # =====================================================
    # Test 4: maxu (符号なし最大値)
    # =====================================================
    li   t0, -1                # 0xFFFFFFFF
    li   t1, 5
    maxu t2, t0, t1            # maxu(0xFFFFFFFF, 5) -> 0xFFFFFFFF (-1)
    li   t3, -1
    li   a0, '4'
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '4'

    # =====================================================
    # Test 5: andn (a & ~b)
    # =====================================================
    li   t0, 0xFF00FF00
    li   t1, 0x0F0F0F0F        # ~t1 = 0xF0F0F0F0
    andn t2, t0, t1            # 0xFF00FF00 & 0xF0F0F0F0 = 0xF000F000
    li   t3, 0xF000F000
    li   a0, '5'
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '5'

    # =====================================================
    # Test 6: orn (a | ~b)
    # =====================================================
    li   t0, 0x00001234
    li   t1, 0x0000FFFF        # ~t1 = 0xFFFF0000
    orn  t2, t0, t1            # 0x00001234 | 0xFFFF0000 = 0xFFFF1234
    li   t3, 0xFFFF1234
    li   a0, '6'
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '6'

    # =====================================================
    # Test 7: xnor (~(a ^ b))
    # =====================================================
    li   t0, 0x55555555
    li   t1, 0xAAAAAAAA        # t0 ^ t1 = 0xFFFFFFFF
    xnor t2, t0, t1            # ~(0xFFFFFFFF) = 0x00000000
    li   t3, 0
    li   a0, '7'
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '7'

    # =====================================================
    # Test 8: clz (Count Leading Zeros)
    # =====================================================
    li   a0, '8'

    # (a) clz(0) == 32
    li   t0, 0
    clz  t2, t0
    li   t3, 32
    bne  t2, t3, fail

    # (b) clz(1) == 31
    li   t0, 1
    clz  t2, t0
    li   t3, 31
    bne  t2, t3, fail

    # (c) clz(0x00010000 = Q16.16の1.0) == 15
    li   t0, 0x00010000
    clz  t2, t0
    li   t3, 15
    bne  t2, t3, fail

    # (d) clz(0xFFFFFFFF = -1) == 0
    li   t0, -1
    clz  t2, t0
    li   t3, 0
    bne  t2, t3, fail
    sb   a0, 0(s11)            # UART: '8'

    # =====================================================
    # Test 9: sext.b (8-bit 符号拡張)
    # =====================================================
    li   a0, '9'

    # (a) 負のバイト: 0x00000080 -> 0xFFFFFF80 (-128)
    li     t0, 0x00000080
    sext.b t2, t0
    li     t3, -128
    bne    t2, t3, fail

    # (b) 正のバイト (上位ゴミあり): 0x1234567F -> 0x0000007F (127)
    li     t0, 0x1234567F
    sext.b t2, t0
    li     t3, 127
    bne    t2, t3, fail
    sb     a0, 0(s11)          # UART: '9'

    # =====================================================
    # Test 10: sext.h (16-bit 符号拡張)
    # =====================================================
    li   a0, 'A'

    # (a) 負のハーフワード: 0x00008000 -> 0xFFFF8000 (-32768)
    li     t0, 0x00008000
    sext.h t2, t0
    li     t3, -32768
    bne    t2, t3, fail

    # (b) 正のハーフワード (上位ゴミあり): 0xABCD7FFF -> 0x00007FFF (32767)
    li     t0, 0xABCD7FFF
    sext.h t2, t0
    li     t3, 32767
    bne    t2, t3, fail
    sb     a0, 0(s11)          # UART: 'A'

    # =====================================================
    # 全テスト成功: "PASS\n" を出力して ret (その後 16B カウンタ自動送信)
    # =====================================================
    li   t0, 'P'
    sb   t0, 0(s11)
    li   t0, 'A'
    sb   t0, 0(s11)
    li   t0, 'S'
    sb   t0, 0(s11)
    sb   t0, 0(s11)
    li   t0, '\n'
    sb   t0, 0(s11)

    li   a0, 1                 # 終了コード 1 (PASS)
    ret

fail:
    # 失敗時: "FAIL:" と失敗したテスト文字 (a0) を出力して停止
    li   t0, 'F'
    sb   t0, 0(s11)
    li   t0, 'A'
    sb   t0, 0(s11)
    li   t0, 'I'
    sb   t0, 0(s11)
    li   t0, 'L'
    sb   t0, 0(s11)
    li   t0, ':'
    sb   t0, 0(s11)
    sb   a0, 0(s11)            # 失敗したテスト番号 ('1'..'9','A')
    li   t0, '\n'
    sb   t0, 0(s11)

    li   a0, 0                 # 終了コード 0 (FAIL)
    ret

